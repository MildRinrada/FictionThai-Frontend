/** One fill-in slot. `hint` says what to write; `length` roughly how much. */
export interface PolicySlot {
  kind: "paragraphs" | "list" | "ordered-list" | "note-info" | "note-warn";
  hint: string;
  length: string;
}

export interface PolicySection {
  heading: string;
  slots: PolicySlot[];
}

export interface PolicyContact {
  icon: IconName;
  /** What this channel is for - structure, safe to state. */
  label: string;
  /** Placeholder: the real address/channel the owner must configure. */
  valueHint: string;
  /** Placeholder: the response time the owner is willing to commit to. */
  slaHint: string;
}

export interface PolicyDoc {
  slug: string;
  group: PolicyGroup;
  title: string;
  /** The English kicker line, mono, above the title. */
  kicker: string;
  /** Scaffold version - bump when the owner publishes a real revision. */
  version: string;
  leadHint: string;
  leadLength: string;
  /** Three bullets for the "สรุปสั้น ๆ" card - hints only. */
  tldrHints: string[];
  sections: PolicySection[];
  contactLeadHint: string;
  contacts: PolicyContact[];
}

const paragraphs = (hint: string, length = "2–4 บรรทัด"): PolicySlot => ({
  kind: "paragraphs",
  hint,
  length,
});

const list = (hint: string, length: string): PolicySlot => ({
  kind: "list",
  hint,
  length,
});

const orderedList = (hint: string, length: string): PolicySlot => ({
  kind: "ordered-list",
  hint,
  length,
});

const noteInfo = (hint: string, length = "1–2 บรรทัด"): PolicySlot => ({
  kind: "note-info",
  hint,
  length,
});

const noteWarn = (hint: string, length = "1–2 บรรทัด"): PolicySlot => ({
  kind: "note-warn",
  hint,
  length,
});

