/** Finds a doc by slug; undefined for unknown slugs (the page 404s). */
export function policyDoc(slug: string): PolicyDoc | undefined {
  return POLICY_DOCS.find((doc) => doc.slug === slug);
}

/** Neighbours in catalog order, wrapping - the prev/next footer nav. */
export function policyNeighbours(slug: string): { prev: PolicyDoc; next: PolicyDoc } {
  const index = Math.max(
    0,
    POLICY_DOCS.findIndex((doc) => doc.slug === slug),
  );
  const prev = POLICY_DOCS[(index - 1 + POLICY_DOCS.length) % POLICY_DOCS.length];
  const next = POLICY_DOCS[(index + 1) % POLICY_DOCS.length];
  return { prev, next };
}

/** Total fill-in slots of one doc - the checklist's per-doc count. */
export function policySlotCount(doc: PolicyDoc): number {
  // lead + tldr bullets + section slots + contact lead + per-contact (value, sla)
  return (
    1 +
    doc.tldrHints.length +
    doc.sections.reduce((sum, section) => sum + section.slots.length, 0) +
    1 +
    doc.contacts.length * 2
  );
}
